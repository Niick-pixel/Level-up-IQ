// Builds assets/packs/rush-hour.json: Rush Hour-style puzzles with their exact minimum move
// counts (breadth-first search over every reachable position). Deterministic for a given seed.
//   node scripts/build-rush-hour.mjs [seconds]
import fs from 'node:fs';
import { makeRng } from '../src/shared/rng.js';
import { randomVehicles, analyse, toBoard } from '../src/renderer/games/rush-hour/logic.js';

const seconds = Number(process.argv[2]) || 120;
const PER_DISTANCE = 30;
const MIN = 3;
const rng = makeRng('mind-gym-rush-hour-v1');
const byMoves = new Map();
const seenBoards = new Set();
const until = Date.now() + seconds * 1000;
let tries = 0;
while (Date.now() < until) {
  tries++;
  const { vs, start } = randomVehicles(rng, rng.int(8, 13));
  const a = analyse(vs, start);
  if (!a || !a.dist.size) continue;
  const max = Math.max(...a.dist.values());
  if (max < MIN) continue;
  // keep the hardest start of this component, plus one random start at each other distance
  const byD = new Map();
  for (const [k, d] of a.dist) if (d >= MIN) (byD.get(d) || byD.set(d, []).get(d)).push(k);
  for (const [d, keys] of byD) {
    const list = byMoves.get(d) || byMoves.set(d, []).get(d);
    if (list.length >= PER_DISTANCE && d !== max) continue;
    const board = toBoard(vs, a.states.get(rng.pick(keys)));
    if (seenBoards.has(board)) continue;
    seenBoards.add(board);
    if (list.length < PER_DISTANCE) list.push({ board, moves: d });
    else list[rng.int(0, list.length - 1)] = { board, moves: d };
  }
}
const puzzles = [...byMoves.keys()].sort((a, b) => a - b).flatMap((d) => byMoves.get(d));
const out = { source: 'Generated by scripts/build-rush-hour.mjs (breadth-first search; moves are exact minimums)', puzzles };
fs.writeFileSync(new URL('../assets/packs/rush-hour.json', import.meta.url), JSON.stringify(out));
const counts = Object.fromEntries([...byMoves].sort((a, b) => a[0] - b[0]).map(([d, l]) => [d, l.length]));
console.log(`${tries} vehicle sets, ${puzzles.length} puzzles`, counts);
